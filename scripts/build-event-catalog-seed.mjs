#!/usr/bin/env node
/**
 * Build the event_catalog seed migration from a dataset JSON ({ meta, events[] }).
 *
 *   node scripts/build-event-catalog-seed.mjs database/seeds/gravel_events_2027.json \
 *     > database/migrations/131_event_catalog_seed_gravel_2027.sql
 *
 *   node scripts/build-event-catalog-seed.mjs database/seeds/run_events_2027.json \
 *     --migration 137 --discipline road_run --with-discipline-index \
 *     > database/migrations/137_event_catalog_seed_run_2027.sql
 *
 * Options (the defaults reproduce migration 131 byte for byte):
 *   --discipline <d>          event_catalog.discipline for events that do not
 *                             carry their own `discipline` (default gravel)
 *   --migration <n>           the migration number in the header (default 131)
 *   --with-discipline-index   also create the index on discipline (137)
 *
 * The insert is ON CONFLICT (id) DO NOTHING: re-running it is safe and never
 * overwrites a row the weekly refresh has already corrected. To push a newer
 * dataset over refreshed rows on purpose, write an explicit UPDATE migration.
 */

import { readFileSync } from 'node:fs';

const args = process.argv.slice(2);
const flag = (name, fallback) => {
  const i = args.indexOf(name);
  return i >= 0 && args[i + 1] ? args[i + 1] : fallback;
};
const path = args.find((a, i) => !a.startsWith('--') && !(i > 0 && ['--discipline', '--migration'].includes(args[i - 1])));
if (!path) {
  console.error(
    'Usage: node scripts/build-event-catalog-seed.mjs <dataset.json> [--discipline d] [--migration n] [--with-discipline-index]',
  );
  process.exit(1);
}
const defaultDiscipline = flag('--discipline', 'gravel');
const migration = Number(flag('--migration', '131'));
const withIndex = args.includes('--with-discipline-index');
const DISCIPLINES = new Set(['gravel', 'road_run', 'trail_run']);

const STATUSES = new Set(['confirmed', 'partial', 'est', 'risk']);
const DATE_RE = /^\d{4}-\d{2}-\d{2}$/;

const { meta, events } = JSON.parse(readFileSync(path, 'utf8'));

const text = (v) => (v === null || v === undefined || v === '' ? 'NULL' : `'${String(v).replace(/'/g, "''")}'`);
const date = (v) => (v && DATE_RE.test(v) ? `'${v}'` : 'NULL');
const num = (v) => (typeof v === 'number' && Number.isFinite(v) ? String(v) : 'NULL');
const nums = (a) => `'{${(Array.isArray(a) ? a : []).filter((n) => Number.isFinite(n)).join(',')}}'::numeric[]`;

const seen = new Set();
const rows = events.map((e) => {
  if (!e.id || seen.has(e.id)) throw new Error(`Missing or duplicate id: ${e.id}`);
  seen.add(e.id);
  if (!DATE_RE.test(e.event_date)) throw new Error(`${e.id}: bad event_date ${e.event_date}`);
  if (!STATUSES.has(e.date_status)) throw new Error(`${e.id}: bad date_status ${e.date_status}`);
  if (!/^[A-Z]{2}$/.test(e.state)) throw new Error(`${e.id}: bad state ${e.state}`);
  const discipline = e.discipline ?? defaultDiscipline;
  if (!DISCIPLINES.has(discipline)) throw new Error(`${e.id}: bad discipline ${discipline}`);
  const season = Number(e.event_date.slice(0, 4));
  return `  (${[
    text(e.id), text(e.name), text(discipline), text(e.city), text(e.state), text(e.region),
    date(e.event_date), text(e.date_status), text(e.date_label), date(e.previous_date),
    text(e.event_type), text(e.distances_text), nums(e.distances_mi), num(e.max_distance_mi),
    text(e.series), text(e.url), text(e.notes), String(season),
  ].join(', ')})`;
});

const index = withIndex
  ? `CREATE INDEX IF NOT EXISTS idx_event_catalog_discipline ON public.event_catalog (discipline);

`
  : '';

process.stdout.write(`-- Migration ${migration}: seed event_catalog with ${meta?.dataset ?? 'events'} (${rows.length} rows).
--
-- Generated by scripts/build-event-catalog-seed.mjs from ${path}
-- (compiled ${meta?.generated ?? 'unknown'}). Do not edit by hand; regenerate.
--
-- ON CONFLICT DO NOTHING: safe to re-run, and never overwrites a row the
-- weekly refresh (api/event-catalog-refresh.js) has corrected.
--
-- APPLY BY HAND after ${migration - 1}.

${index}INSERT INTO public.event_catalog
  (id, name, discipline, city, state, region, event_date, date_status, date_label, previous_date,
   event_type, distances_text, distances_mi, max_distance_mi, series, url, notes, season)
VALUES
${rows.join(',\n')}
ON CONFLICT (id) DO NOTHING;
`);
